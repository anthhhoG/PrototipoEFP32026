    private void mostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mostrarActionPerformed
 DefaultTableModel modelo = (DefaultTableModel) tblCarreras.getModel();

    // Limpiar la tabla
    modelo.setRowCount(0);

    CarrerasDAO dao = new CarrerasDAO();

    List<clsCarreras> lista = dao.listar();

    for (clsCarreras carrera : lista) {

        Object[] fila = {
            carrera.getCodigoCarrera(),
            carrera.getNombreCarrera(),
            carrera.getCodigoFacultad(),
            carrera.getEstatusCarrera()
        };

        modelo.addRow(fila);
    }

    JOptionPane.showMessageDialog(this,
            "Datos actualizados correctamente");        // TODO add your handling code here:
    }//GEN-LAST:event_mostrarActionPerformed


    private void insertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_insertarActionPerformed
clsCarreras carrera = new clsCarreras();

    carrera.setCodigoCarrera(txtCodigoCarrera.getText());
    carrera.setNombreCarrera(txtNombreCarrera.getText());
    carrera.setCodigoFacultad(txtCodigoFacultad.getText());
    carrera.setEstatusCarrera(txtEstatusCarrera.getText());

    CarrerasDAO dao = new CarrerasDAO();

    if (dao.insertar(carrera)) {
        JOptionPane.showMessageDialog(this,
                "Registro insertado correctamente");
        cargarTabla();
        limpiarCampos();
    } else {
        JOptionPane.showMessageDialog(this,
                "Error al insertar");
    }
    }//GEN-LAST:event_insertarActionPerformed

    private void consulActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_consulActionPerformed
 String codigo = txtCodigoCarrera.getText();

    CarrerasDAO dao = new CarrerasDAO();

    clsCarreras carrera = dao.buscarPorCodigo(codigo);

    if (carrera != null) {

        txtNombreCarrera.setText(
                carrera.getNombreCarrera());

        txtCodigoFacultad.setText(
                carrera.getCodigoFacultad());

        txtEstatusCarrera.setText(
                carrera.getEstatusCarrera());

    } else {

        JOptionPane.showMessageDialog(this,
                "Carrera no encontrada");
    }        // TODO add your handling code here:
    }//GEN-LAST:event_consulActionPerformed

